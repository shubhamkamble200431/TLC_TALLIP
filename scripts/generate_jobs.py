#!/usr/bin/env python
"""
Job generation for the 48-run factorial + baselines (brief section 34).

Does NOT launch anything.  Emits shell / SLURM scripts that a human runs:

    jobs/factorial_jobs.sh        one `run_factorial.py --config .. --seed ..` per line,
                                  round-robin pinned to detected GPUs, run with nohup
    jobs/factorial_jobs.slurm     a SLURM array over the same 48 NLLB tasks
    jobs/mbart50_jobs.sh          the SAME 16 x 3 = 48 grid on mBART-50-M2M
    jobs/mbart50_jobs.slurm       a SLURM array over the 48 mBART tasks
    jobs/commands.txt             plain command list (for manual dispatch)

GPU discovery is via torch; large training jobs are not stacked on one GPU
unless --jobs-per-gpu > 1.

Example:
  python scripts/generate_jobs.py --dataset v2 --seeds 42 43 44 --gpus 4 5 7
"""
import _paths  # noqa: F401

import argparse
import os
import stat

from src.config import ALL_CASE_IDS
from src.experiments.factorial import enumerate_runs
from src.utils.gpu import detect_gpus, round_robin_assign

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _chmod_x(path):
    os.chmod(path, os.stat(path).st_mode | stat.S_IEXEC | stat.S_IXGRP)


def _grid_cmds(script, dataset, seeds, extra, prefix=""):
    """One (job-id, command) per (X-ABCD config, seed) — 16 x len(seeds)."""
    cmds = []
    for cid, seed in enumerate_runs("all", seeds):
        cmds.append((f"{prefix}{cid}_seed{seed}",
                     f"python scripts/{script} --config {cid} --seed {seed} "
                     f"--dataset {dataset} --skip-completed --resume{extra}"))
    return cmds


def write_bash(path, cmds, gpus, jobs_per_gpu, conda_env, workdir, log_dir):
    lines = [
        "#!/bin/bash",
        "# Auto-generated by scripts/generate_jobs.py — review before running.",
        "# Sequential per-GPU dispatch with nohup; one large job per GPU at a time.",
        "set -u",
        f"cd {workdir}",
        f'source /raid/chandresh/miniconda3/etc/profile.d/conda.sh && conda activate {conda_env}',
        "export TRANSFORMERS_OFFLINE=0 HF_HUB_OFFLINE=0 HF_DATASETS_OFFLINE=0  # box sets =1; HF cache is partial",
        f"mkdir -p {log_dir}",
        "",
    ]
    assign = round_robin_assign([c[0] for c in cmds], gpus if gpus else [None])
    by_gpu = {}
    for (jid, gpu), (_, cmd) in zip(assign, cmds):
        by_gpu.setdefault(gpu, []).append((jid, cmd))

    pids = []
    for gpu, jobs in by_gpu.items():
        dev = "" if gpu is None else f"CUDA_VISIBLE_DEVICES={gpu} "
        sub = " && \\\n    ".join(
            f'{dev}{cmd} > {log_dir}/{jid}.out 2> {log_dir}/{jid}.err' for jid, cmd in jobs
        )
        lines += [f"# ---- GPU {gpu} : {len(jobs)} jobs sequential ----",
                  f"( {sub} ) &",
                  f"PID_{gpu if gpu is not None else 'x'}=$!",
                  ""]
        pids.append(f"PID_{gpu if gpu is not None else 'x'}")
    lines += ['echo "Launched: ' + " ".join(f"${p}" for p in pids) + '"',
              "wait", 'echo "All GPU streams finished."', ""]
    with open(path, "w") as f:
        f.write("\n".join(lines))
    _chmod_x(path)


def write_slurm(path, cmds, job_name, conda_env, workdir, partition, log_dir):
    body = [
        "#!/bin/bash",
        f"#SBATCH --job-name={job_name}",
        f"#SBATCH --partition={partition}",
        "#SBATCH --nodes=1",
        "#SBATCH --ntasks=1",
        "#SBATCH --gres=gpu:1",
        "#SBATCH --cpus-per-task=8",
        "#SBATCH --mem=64G",
        "#SBATCH --time=1-00:00:00",
        f"#SBATCH --array=0-{len(cmds) - 1}%4",
        f"#SBATCH --output={log_dir}/%x_%A_%a.out",
        f"#SBATCH --error={log_dir}/%x_%A_%a.err",
        "",
        f"cd {workdir}",
        f"source /raid/chandresh/miniconda3/etc/profile.d/conda.sh && conda activate {conda_env}",
        "export TRANSFORMERS_OFFLINE=0 HF_HUB_OFFLINE=0 HF_DATASETS_OFFLINE=0",
        f"mkdir -p {log_dir}",
        "",
        "CMDS=(",
    ]
    for _, cmd in cmds:
        body.append(f'  "{cmd}"')
    body += [")", 'echo "task $SLURM_ARRAY_TASK_ID : ${CMDS[$SLURM_ARRAY_TASK_ID]}"',
             'eval "${CMDS[$SLURM_ARRAY_TASK_ID]}"', ""]
    with open(path, "w") as f:
        f.write("\n".join(body))
    _chmod_x(path)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dataset", default="v2")
    ap.add_argument("--seeds", nargs="*", type=int, default=[42, 43, 44])
    ap.add_argument("--gpus", nargs="*", type=int, default=None, help="GPU ids (default: torch-detected)")
    ap.add_argument("--jobs-per-gpu", type=int, default=1)
    ap.add_argument("--conda-env", default="emnlp")
    ap.add_argument("--partition", default="gpu")
    ap.add_argument("--out-dir", default="jobs")
    ap.add_argument("--log-dir", default="jobs/logs")
    ap.add_argument("--extra", default="", help="extra flags appended to every run_factorial.py command")
    args = ap.parse_args()

    gpus = args.gpus if args.gpus is not None else detect_gpus()
    os.makedirs(args.out_dir, exist_ok=True)
    extra = (" " + args.extra.strip()) if args.extra.strip() else ""

    fac = _grid_cmds("run_factorial.py", args.dataset, args.seeds, extra)
    write_bash(os.path.join(args.out_dir, "factorial_jobs.sh"), fac, gpus, args.jobs_per_gpu,
               args.conda_env, REPO, args.log_dir)
    write_slurm(os.path.join(args.out_dir, "factorial_jobs.slurm"), fac, "tlc_tallip_factorial",
                args.conda_env, REPO, args.partition, args.log_dir)

    # mBART-50-M2M: the SAME 16 x 3 = 48 grid, for cross-architecture generalisability
    mb = _grid_cmds("run_mbart50.py", args.dataset, args.seeds, extra, prefix="mbart50_")
    write_bash(os.path.join(args.out_dir, "mbart50_jobs.sh"), mb, gpus, args.jobs_per_gpu,
               args.conda_env, REPO, args.log_dir)
    write_slurm(os.path.join(args.out_dir, "mbart50_jobs.slurm"), mb, "tlc_tallip_mbart50",
                args.conda_env, REPO, args.partition, args.log_dir)

    with open(os.path.join(args.out_dir, "commands.txt"), "w") as f:
        for _, cmd in fac + mb:
            f.write(cmd + "\n")

    print(f"[jobs] detected GPUs: {gpus or '(none / CPU)'}")
    print(f"[jobs] {len(fac)} NLLB factorial tasks -> {args.out_dir}/factorial_jobs.sh + .slurm")
    print(f"[jobs] {len(mb)} mBART-50 factorial tasks -> {args.out_dir}/mbart50_jobs.sh + .slurm")
    print(f"[jobs] plain list                    -> {args.out_dir}/commands.txt")
    print("[jobs] nothing launched. Review, then: bash jobs/factorial_jobs.sh   (or sbatch ...slurm)")


if __name__ == "__main__":
    main()
