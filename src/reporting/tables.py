def table_3seed_overall(summary_csv: str, out_dir: str,
                        metrics: Sequence[str] = ("bleu", "chrf2", "ter", "meteor", "bertscore", "comet")) -> str:
    df = pd.read_csv(summary_csv).set_index("config")
    header = ["Config", "Intervention"] + [m.upper() for m in metrics]
    rows = []
    for cid in [c for c in ALL_CASE_IDS if c in df.index]:
        r = df.loc[cid]
        cells = [cid, case_label(cid)]
        for m in metrics:
            cells.append(_pm(r.get(f"{m}_mean"), r.get(f"{m}_std")))
        rows.append(cells)
    return _write(out_dir, "table_3seed_overall.tex", _latex_document_table(
        rows, header,
        "Overall test performance (mean $\\pm$ std over seeds 42/43/44, v2).",
        "tab:3seed_overall"))


def table_3seed_bucket(bucket_csv: str, out_dir: str, metric: str = "bleu") -> str:
    df = pd.read_csv(bucket_csv)
    g = df.groupby(["config", "bucket"])[metric].agg(["mean", "std"])
    buckets = ["B1", "B2", "B3", "B4", "B5"]
    header = ["Config"] + buckets
    rows = []
    for cid in [c for c in ALL_CASE_IDS if c in df["config"].unique()]:
        cells = [cid]
        for b in buckets:
            try:
                mu, sd = g.loc[(cid, b)]
            except KeyError:
                cells.append("--")
                continue
            cells.append(_pm(mu, sd, nd=1))
        rows.append(cells)
    return _write(out_dir, "table_3seed_bucket.tex", _latex_document_table(
        rows, header,
        f"Per-bucket {metric.upper()} (mean $\\pm$ std over 3 seeds).",
        f"tab:3seed_bucket_{metric}"))


def table_bbs_ablation(bbs_ablation_csv: str, out_dir: str) -> str:
    """Columns: Variant | w1..w5 | BLEU | chrF2 | COMET | B5 BLEU | Length Error."""
    df = pd.read_csv(bbs_ablation_csv)
    header = ["BBS variant", "$w_1$", "$w_2$", "$w_3$", "$w_4$", "$w_5$",
             "BLEU", "chrF2", "COMET", "B5 BLEU", "Len.\\ err."]
    rows = []
    for _, r in df.iterrows():
        rows.append([
            str(r.get("variant", r.get("bbs_variant", ""))),
            _fmt(r.get("w1"), 2), _fmt(r.get("w2"), 2), _fmt(r.get("w3"), 2),
            _fmt(r.get("w4"), 2), _fmt(r.get("w5"), 2),
            _pm(r.get("bleu_mean", r.get("bleu")), r.get("bleu_std")),
            _pm(r.get("chrf2_mean", r.get("chrf2")), r.get("chrf2_std")),
            _pm(r.get("comet_mean", r.get("comet")), r.get("comet_std")),
            _pm(r.get("b5_bleu_mean", r.get("b5_bleu")), r.get("b5_bleu_std")),
            _pm(r.get("length_error_mean", r.get("length_error")), r.get("length_error_std")),
        ])
    return _write(out_dir, "table_bbs_ablation.tex", _latex_document_table(
        rows, header,
        "BBS weight-vector ablation (uniform / manual / grid-selected / alternatives). "
        "Weights are mean-normalised (sum $=5$). Selection used validation only.",
        "tab:bbs_ablation"))


def table_mbart_baseline(summary_csv: str, mbart_summary_csv: str, out_dir: str,
                         nllb_refs: Sequence[str] = ("X-0000", "X-1101")) -> str:
    metrics = ["bleu", "chrf2", "ter", "meteor", "bertscore", "comet"]
    header = ["System"] + [m.upper() for m in metrics]
    rows = []
    mb = pd.read_csv(mbart_summary_csv).set_index("config")
    for cid in mb.index:
        r = mb.loc[cid]
        rows.append(["mBART-50-M2M"] + [_pm(r.get(f"{m}_mean"), r.get(f"{m}_std")) for m in metrics])
    nl = pd.read_csv(summary_csv).set_index("config")
    for cid in nllb_refs:
        if cid in nl.index:
            r = nl.loc[cid]
            rows.append([f"NLLB {cid} ({case_label(cid)})"]
                        + [_pm(r.get(f"{m}_mean"), r.get(f"{m}_std")) for m in metrics])
    return _write(out_dir, "table_mbart_baseline.tex", _latex_document_table(
        rows, header,
        "mBART-50 many-to-many baseline vs NLLB reference configurations "
        "(mean $\\pm$ std over 3 seeds, v2, identical test set and decoding).",
        "tab:mbart_baseline"))


def table_factorial_effects(effects_csv: str, out_dir: str, metric_label: str = "BLEU") -> str:
    df = pd.read_csv(effects_csv)
    header = ["Term", "Coef.", "Effect (2$\\times$)", "SE", "95\\% CI", "$p$", ""]
    rows = []
    for _, r in df.iterrows():
        ci = f"[{_fmt(r['ci_low'], 3)}, {_fmt(r['ci_high'], 3)}]"
        star = "" if r["term"] == "Intercept" else ("$\\ast$" if r.get("significant") else "")
        rows.append([
            r["term"], _fmt(r["coefficient"], 3), _fmt(r["effect"], 3),
            _fmt(r["std_error"], 3), ci, _fmt(r["p_value"], 4), star,
        ])
    return _write(out_dir, "table_factorial_effects.tex", _latex_document_table(
        rows, header,
        f"Saturated $2^4$ factorial effects on {metric_label} "
        "(A=BBS, B=TLC, C=RoPE, D=ALiBi; contrast coding $\\pm1$; "
        "replicated over 3 seeds). $\\ast$: $p<0.05$.",
        "tab:factorial_effects", col_spec="lrrrccc"))


def table_length_metrics(summary_csv: str, out_dir: str) -> str:
    metrics = ["length_ratio", "absolute_length_error", "relative_length_error",
               "premature_eos_rate", "overgeneration_rate", "truncation_rate"]
    short = ["Len. ratio", "Abs. len. err.", "Rel. len. err.", "Premat. EOS", "Over-gen.", "Trunc."]
    df = pd.read_csv(summary_csv).set_index("config")
    header = ["Config"] + short
    rows = []
    for cid in [c for c in ALL_CASE_IDS if c in df.index]:
        r = df.loc[cid]
        rows.append([cid] + [_pm(r.get(f"{m}_mean"), r.get(f"{m}_std"), nd=3) for m in metrics])
    return _write(out_dir, "table_length_metrics.tex", _latex_document_table(
        rows, header,
        "Length-behaviour metrics on the test set (mean $\\pm$ std over 3 seeds).",
        "tab:length_metrics"))


def table_domain_length(domain_csv: str, out_dir: str, metric: str = "bleu") -> str:
    """Rows = dataset/domain, Columns = B1..B5, cell = metric (brief section 16)."""
    df = pd.read_csv(domain_csv)
    buckets = ["B1", "B2", "B3", "B4", "B5"]
    header = ["Domain"] + buckets
    rows = []
    for dom, sub in df.groupby("domain"):
        g = sub.groupby("bucket")[metric].mean()
        rows.append([str(dom)] + [_fmt(g.get(b), 1) for b in buckets])
    return _write(out_dir, "table_domain_length.tex", _latex_document_table(
        rows, header,
        f"Domain $\\times$ length-bucket {metric.upper()} (SanHinCorp vs Himsanskritam).",
        f"tab:domain_length_{metric}"))
