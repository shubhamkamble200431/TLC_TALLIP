"""
LaTeX table generation (brief section 24).

Every table is built from the CSV/JSON result files — no hand-typed numbers.
Full precision is kept in the CSVs; rounding happens only here, in the
presentation layer.  3-seed cells are rendered as  mean $\\pm$ std.
"""
from __future__ import annotations

import os
from typing import List, Optional, Sequence

import numpy as np
import pandas as pd

from src.config import ALL_CASE_IDS, case_label
from src.utils.io import ensure_dir


def _fmt(x, nd=2):
    try:
        if x is None or (isinstance(x, float) and not np.isfinite(x)):
            return "--"
        return f"{float(x):.{nd}f}"
    except Exception:
        return "--"


def _pm(mean, std, nd=2):
    if mean is None or (isinstance(mean, float) and not np.isfinite(mean)):
        return "--"
    s = "" if (std is None or not np.isfinite(std)) else f"\\,$\\pm$\\,{float(std):.{nd}f}"
    return f"{float(mean):.{nd}f}{s}"


def _latex_document_table(body_rows: List[List[str]], header: List[str], caption: str,
                          label: str, col_spec: Optional[str] = None) -> str:
    ncol = len(header)
    col_spec = col_spec or ("l" + "r" * (ncol - 1))
    lines = [
        "% Auto-generated by src/reporting/tables.py — do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\small",
        f"\\begin{{tabular}}{{{col_spec}}}",
        "\\toprule",
        " & ".join(header) + " \\\\",
        "\\midrule",
    ]
    for r in body_rows:
        lines.append(" & ".join(r) + " \\\\")
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        "\\end{table}",
        "",
    ]
    return "\n".join(lines)


def _write(out_dir: str, name: str, text: str) -> str:
    ensure_dir(out_dir)
    path = os.path.join(out_dir, name)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    return path


